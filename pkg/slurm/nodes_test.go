func TestAddNodesToConf_NewPartitionKeepsMainDefault(t *testing.T) {
	// Partition all, written again after the last managed worker took it
	// along, does not become the default when slurm.conf declares one of
	// its own: it would win, as sind-nodes.conf comes last.
	main := config.Section{Content: "PartitionName=debug Nodes=ALL Default=YES\n"}
	workers := []NodeEntry{{Name: "worker-0", CPUs: 1, MemoryMB: 512}}
	created := GenerateNodesConf(workers, main)
	require.Contains(t, created, "PartitionName=all Nodes=worker-0 Default=NO\n")
	emptied := RemoveNodesFromConf(created, []string{"worker-0"})
	require.Equal(t, "# Generated by sind\n", emptied)

	conf, err := ReadSlurmConf(confFiles(map[string]string{SlurmConfPath: GenerateSlurmConf("dev", main, ConfOptions{})}))
	require.NoError(t, err)
	result := AddNodesToConf(emptied, []NodeEntry{{Name: "worker-1", CPUs: 1, MemoryMB: 512}}, conf)
	assert.Equal(t, "# Generated by sind\n"+
		"NodeName=worker-1 CPUs=1 RealMemory=512 State=UNKNOWN\n"+
		"PartitionName=all Nodes=worker-1 Default=NO\n", result)
}

func TestAddNodesToConf_KeepsPartitionLine(t *testing.T) {
	// Only the Nodes= list changes: Default=NO, written when slurm.main
	// declares its own default partition, and edits made by hand stay.
	existing := "# Generated by sind\n" +
		"NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n" +
		"PartitionName=all Nodes=worker-0 Default=NO DefaultTime=10\n"

	result := AddNodesToConf(existing, []NodeEntry{{Name: "worker-1", CPUs: 2, MemoryMB: 2048}}, config.Section{})
	assert.Contains(t, result, "PartitionName=all Nodes=worker-0,worker-1 Default=NO DefaultTime=10\n")

	result = RemoveNodesFromConf(result, []string{"worker-0"})
	assert.Contains(t, result, "PartitionName=all Nodes=worker-1 Default=NO DefaultTime=10\n")
}

func TestPartitionLine(t *testing.T) {
	assert.Equal(t, "PartitionName=all Nodes=worker-1 Default=NO", partitionLine("PartitionName=all nodes=worker-0 Default=NO", []string{"worker-1"}))
	// A line edited to lose its Nodes= gets them back at the end.
	assert.Equal(t, "PartitionName=all Default=NO Nodes=worker-1", partitionLine("PartitionName=all  Default=NO", []string{"worker-1"}))
}

func splitLines(s string) []string {
	s = strings.TrimRight(s, "\n")
	return strings.Split(s, "\n")
}

