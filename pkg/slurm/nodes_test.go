func TestParseMemoryMB(t *testing.T) {
	got, err := ParseMemoryMB("2gb")
	require.NoError(t, err)
	assert.Equal(t, 2048, got)

	_, err = ParseMemoryMB("2x")
	assert.Error(t, err)
}
