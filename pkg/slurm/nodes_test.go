// generateNodesConf generates sind-nodes.conf for the managed workers of
// nodes.
func generateNodesConf(t *testing.T, nodes []config.Node) string {
	t.Helper()
	workers, err := ManagedWorkers(nodes)
	require.NoError(t, err)
	return GenerateNodesConf(workers, config.Section{})
}

// --- ManagedWorkers ---

func TestManagedWorkers(t *testing.T) {
	workers, err := ManagedWorkers([]config.Node{
		{Role: "controller", CPUs: 1, Memory: "bogus"},
		{Role: "worker", Count: 2, CPUs: 2, Memory: "1.5g"},
		{Role: "worker", CPUs: 1, Memory: "bogus", Managed: testutil.Ptr(false)},
		{Role: "worker", CPUs: 4, Memory: "2GiB"},
	})
	require.NoError(t, err)
	assert.Equal(t, []NodeEntry{
		{Name: "worker-0", CPUs: 2, MemoryMB: 1536},
		{Name: "worker-1", CPUs: 2, MemoryMB: 1536},
		{Name: "worker-3", CPUs: 4, MemoryMB: 2048},
	}, workers)
}

func TestManagedWorkers_InvalidMemory(t *testing.T) {
	// A memory limit sind cannot convert is an error, never RealMemory=0.
	_, err := ManagedWorkers([]config.Node{
		{Role: "worker", Count: 2, CPUs: 1, Memory: "512m"},
		{Role: "worker", CPUs: 1, Memory: "2x"},
	})
	require.ErrorContains(t, err, `worker-2: invalid memory "2x"`)
}

func TestGenerateNodesConf_MainDefaultPartition(t *testing.T) {
	// A default partition of slurm.main's own stays the default, although
	// sind-nodes.conf comes after it: partition all is not the default.
	workers := []NodeEntry{{Name: "worker-0", CPUs: 1, MemoryMB: 512}}
	for _, tt := range []struct {
		main string
		want string
	}{
		{"", "Default=YES"},
		{"PartitionName=debug Nodes=ALL Default=YES\n", "Default=NO"},
		{"PartitionName=debug Nodes=ALL default=true MaxTime=30\n", "Default=NO"},
		{"PartitionName=debug Nodes=ALL Default=1\n", "Default=NO"},
		{"PartitionName=debug Nodes=ALL Default=UP\n", "Default=NO"},
		{"PartitionName=debug Nodes=ALL Default=NO\n", "Default=YES"},
		{"PartitionName=debug Nodes=ALL # Default=YES\n", "Default=YES"},
		{"PartitionName=DEFAULT Default=YES DefaultTime=10\n", "Default=YES"},
		{"NodeName=n1 Default=YES\n", "Default=YES"},
		{"Default=YES\n", "Default=YES"},
	} {
		conf := GenerateNodesConf(workers, config.Section{Content: tt.main})
		assert.Contains(t, conf, "PartitionName=all Nodes=worker-0 "+tt.want+"\n", tt.main)
	}

	frag := config.Section{Fragments: map[string]string{"a": "MaxNodeCount=10\n", "b": "PartitionName=debug Nodes=ALL Default=YES\n"}}
	assert.Contains(t, GenerateNodesConf(workers, frag), "Default=NO\n")
}

// --- DefMemPerCPU ---

func TestDefMemPerCPU(t *testing.T) {
	assert.Equal(t, 0, DefMemPerCPU(nil))
	assert.Equal(t, 512, DefMemPerCPU([]NodeEntry{{Name: "worker-0", CPUs: 1, MemoryMB: 512}}))
	// The smallest memory per CPU of all workers, rounded down.
	assert.Equal(t, 341, DefMemPerCPU([]NodeEntry{
		{Name: "worker-0", CPUs: 2, MemoryMB: 2048},
		{Name: "worker-1", CPUs: 3, MemoryMB: 1024},
		{Name: "worker-2", CPUs: 1, MemoryMB: 512},
	}))
	// No default when a worker has less than 1 MB per CPU.
	assert.Equal(t, 0, DefMemPerCPU([]NodeEntry{
		{Name: "worker-0", CPUs: 8, MemoryMB: 6},
		{Name: "worker-1", CPUs: 1, MemoryMB: 512},
	}))
	// A worker without CPUs (no ApplyDefaults) counts as one CPU.
	assert.Equal(t, 512, DefMemPerCPU([]NodeEntry{{Name: "worker-0", MemoryMB: 512}}))
}

