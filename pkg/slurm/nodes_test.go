func TestAddNodesToConf_PreservesComment(t *testing.T) {
	existing := "# Generated by sind\n" +
		"NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n" +
		"PartitionName=all Nodes=worker-0 Default=YES MaxTime=INFINITE State=UP\n"

	result := AddNodesToConf(existing, []NodeEntry{
		{Name: "worker-1", CPUs: 2, MemoryMB: 2048},
	})

	assert.True(t, len(result) > 0)
	lines := splitLines(result)
	assert.Equal(t, "# Generated by sind", lines[0])
}

func TestAddNodesToConf_ReplacesExistingNode(t *testing.T) {
	// A node a failed add left behind is defined once, with the new values:
	// Slurm refuses to start with a node defined twice.
	existing := "# Generated by sind\n" +
		"NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n" +
		"NodeName=worker-1 CPUs=1 RealMemory=512 State=UNKNOWN\n" +
		"PartitionName=all Nodes=worker-0,worker-1 Default=YES MaxTime=INFINITE State=UP\n"

	result := AddNodesToConf(existing, []NodeEntry{
		{Name: "worker-1", CPUs: 4, MemoryMB: 8192},
		{Name: "worker-2", CPUs: 4, MemoryMB: 8192},
	})

	assert.Equal(t, "# Generated by sind\n"+
		"NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n"+
		"NodeName=worker-1 CPUs=4 RealMemory=8192 State=UNKNOWN\n"+
		"NodeName=worker-2 CPUs=4 RealMemory=8192 State=UNKNOWN\n"+
		"PartitionName=all Nodes=worker-0,worker-1,worker-2 Default=YES MaxTime=INFINITE State=UP\n", result)
}

func TestAddNodesToConf_DropsDuplicates(t *testing.T) {
	// Duplicate definitions, as earlier sind versions could leave, and
	// duplicate new entries are written once.
	existing := "# Generated by sind\n" +
		"NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n" +
		"NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n" +
		"NodeName=worker-1 CPUs=1 RealMemory=512 State=UNKNOWN\n" +
		"NodeName=worker-1 CPUs=2 RealMemory=1024 State=UNKNOWN\n" +
		"PartitionName=all Nodes=worker-0,worker-0,worker-1,worker-1 Default=YES MaxTime=INFINITE State=UP\n"

	result := AddNodesToConf(existing, []NodeEntry{
		{Name: "worker-1", CPUs: 4, MemoryMB: 8192},
		{Name: "worker-2", CPUs: 4, MemoryMB: 8192},
		{Name: "worker-2", CPUs: 4, MemoryMB: 8192},
	})

	assert.Equal(t, "# Generated by sind\n"+
		"NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n"+
		"NodeName=worker-1 CPUs=4 RealMemory=8192 State=UNKNOWN\n"+
		"NodeName=worker-2 CPUs=4 RealMemory=8192 State=UNKNOWN\n"+
		"PartitionName=all Nodes=worker-0,worker-1,worker-2 Default=YES MaxTime=INFINITE State=UP\n", result)
}

func TestRemoveNodesFromConf_RemovesDuplicates(t *testing.T) {
	existing := "NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n" +
		"NodeName=worker-1 CPUs=1 RealMemory=512 State=UNKNOWN\n" +
		"NodeName=worker-1 CPUs=2 RealMemory=1024 State=UNKNOWN\n" +
		"PartitionName=all Nodes=worker-0,worker-1,worker-1 Default=YES MaxTime=INFINITE State=UP\n"

	result := RemoveNodesFromConf(existing, []string{"worker-1"})

	assert.Equal(t, "NodeName=worker-0 CPUs=2 RealMemory=2048 State=UNKNOWN\n"+
		"PartitionName=all Nodes=worker-0 Default=YES MaxTime=INFINITE State=UP\n", result)
}

func TestNodesConf_RemoveUnlistedNodeChangesNothing(t *testing.T) {
	// What sind generates comes back unchanged when the nodes to remove are
	// not in it, which lets WorkerRemove skip the write and reconfigure.
	workers, err := ManagedWorkers([]config.Node{{Role: config.RoleWorker, Count: 2, CPUs: 2, Memory: "2g"}})
	require.NoError(t, err)
	conf := GenerateNodesConf(workers)
	added := AddNodesToConf(conf, []NodeEntry{{Name: "worker-2", CPUs: 1, MemoryMB: 512}})

	assert.Equal(t, conf, RemoveNodesFromConf(conf, []string{"worker-7"}))
	assert.Equal(t, conf, RemoveNodesFromConf(added, []string{"worker-2"}))
}

