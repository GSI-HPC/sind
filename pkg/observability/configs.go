// Retention of the stack's metrics and logs. There is no realm-level
// configuration to set them in, and per-cluster settings would conflict.
const (
	retentionTime = "7d"
	retentionSize = "2GB"
	lokiRetention = "168h"
)

// prometheusConfigPath is Prometheus's configuration file.
const prometheusConfigPath = "/etc/prometheus/sind.yml"

// prometheusConfig is Prometheus's configuration: it scrapes nothing, as
// Alloy writes all series to it.
const prometheusConfig = `# Generated by sind. Alloy writes every series through the remote-write
# receiver; Prometheus scrapes nothing itself.
global:
  evaluation_interval: 1m
`

// prometheusArgs are the arguments of Prometheus's command: the
// configuration, its volume, the remote-write receiver and retention.
var prometheusArgs = []string{
	"--config.file=" + prometheusConfigPath,
	"--storage.tsdb.path=/prometheus",
	"--storage.tsdb.retention.time=" + retentionTime,
	"--storage.tsdb.retention.size=" + retentionSize,
	"--web.enable-remote-write-receiver",
}

// lokiConfigPath is Loki's configuration file.
const lokiConfigPath = "/etc/loki/sind.yaml"

// lokiArgs are the arguments of Loki's command.
var lokiArgs = []string{"-config.file=" + lokiConfigPath}

// lokiConfig is Loki's configuration: the image's local-config.yaml, a
// single process with filesystem storage under its volume, plus retention,
// which the stock configuration lacks (it keeps logs forever), and without
// usage reports.
const lokiConfig = `# Generated by sind.
auth_enabled: false

server:
  http_listen_port: ` + LokiPort + `
  grpc_listen_port: 9096
  log_level: warn

common:
  instance_addr: 127.0.0.1
  path_prefix: /loki
  storage:
    filesystem:
      chunks_directory: /loki/chunks
      rules_directory: /loki/rules
  replication_factor: 1
  ring:
    kvstore:
      store: inmemory

query_range:
  results_cache:
    cache:
      embedded_cache:
        enabled: true
        max_size_mb: 100

schema_config:
  configs:
    - from: 2020-10-24
      store: tsdb
      object_store: filesystem
      schema: v13
      index:
        prefix: index_
        period: 24h

limits_config:
  retention_period: ` + lokiRetention + `

compactor:
  working_directory: /loki/compactor
  retention_enabled: true
  delete_request_store: filesystem

analytics:
  reporting_enabled: false
`

// alloyArgs are the arguments of Alloy's command: its configuration, its
// UI on the mesh (Alloy listens on 127.0.0.1 by default, which would hide
// /-/ready and /-/reload from the mesh), its state on its volume, and no
// usage reports.
var alloyArgs = []string{
	"run", AlloyConfigPath,
	"--server.http.listen-addr=0.0.0.0:" + AlloyPort,
	"--storage.path=/var/lib/alloy/data",
	"--disable-reporting",
}

// Grafana's provisioning.
const (
	grafanaProvisioning = "/etc/grafana/provisioning"
	// DashboardsDir is where the sind dashboards are provisioned from.
	DashboardsDir = grafanaProvisioning + "/dashboards/sind"
	// PrometheusUID and LokiUID are the fixed UIDs of the datasources,
	// which the dashboards refer to.
	PrometheusUID = "sind-prometheus"
	LokiUID       = "sind-loki"
	// homeDashboard is the dashboard Grafana opens on: the Slurm cluster
	// overview.
	homeDashboard = DashboardsDir + "/slurm-cluster.json"
)

// grafanaEnv is Grafana's environment: anyone who reaches it is an
// anonymous org Admin, with no login at all (there is no data or access
// to protect, and admin:admin over basic auth would only fall through to
// the anonymous identity), and Grafana fetches nothing from the internet:
// no plugin installs or updates, no update checks, news, gravatars or
// external snapshots, and no usage reports.
var grafanaEnv = []string{
	"GF_AUTH_ANONYMOUS_ENABLED=true",
	"GF_AUTH_ANONYMOUS_ORG_ROLE=Admin",
	"GF_AUTH_DISABLE_LOGIN_FORM=true",
	"GF_AUTH_DISABLE_LOGIN=true",
	"GF_AUTH_BASIC_ENABLED=false",
	"GF_AUTH_DISABLE_SIGNOUT_MENU=true",
	"GF_PLUGINS_PREINSTALL_DISABLED=true",
	"GF_PLUGINS_PLUGIN_ADMIN_ENABLED=false",
	"GF_PLUGINS_PUBLIC_KEY_RETRIEVAL_DISABLED=true",
	"GF_ANALYTICS_REPORTING_ENABLED=false",
	"GF_ANALYTICS_CHECK_FOR_UPDATES=false",
	"GF_ANALYTICS_CHECK_FOR_PLUGIN_UPDATES=false",
	"GF_ANALYTICS_FEEDBACK_LINKS_ENABLED=false",
	"GF_NEWS_NEWS_FEED_ENABLED=false",
	"GF_SECURITY_DISABLE_GRAVATAR=true",
	"GF_SNAPSHOTS_EXTERNAL_ENABLED=false",
	"GF_DASHBOARDS_DEFAULT_HOME_DASHBOARD_PATH=" + homeDashboard,
	// Refreshing faster than the shortest scrape interval shows nothing
	// new and only loads Grafana.
	"GF_DASHBOARDS_MIN_REFRESH_INTERVAL=15s",
}

// grafanaDatasources provisions Prometheus and Loki with fixed UIDs, which
// no one can change in the UI.
func grafanaDatasources(realm string) string {
	return fmt.Sprintf(`# Generated by sind.
apiVersion: 1
datasources:
  - name: Prometheus
    type: prometheus
    uid: %s
    access: proxy
    url: http://%s:%s
    isDefault: true
    editable: false
  - name: Loki
    type: loki
    uid: %s
    access: proxy
    url: http://%s:%s
    editable: false
`, PrometheusUID, ContainerName(realm, ServicePrometheus), PrometheusPort,
		LokiUID, ContainerName(realm, ServiceLoki), LokiPort)
}

// grafanaDashboardProvider provisions the sind dashboards into the folder
// sind. They cannot be changed in place, only copied.
const grafanaDashboardProvider = `# Generated by sind.
apiVersion: 1
providers:
  - name: sind
    folder: sind
    type: file
    allowUiUpdates: false
    disableDeletion: true
    options:
      path: ` + DashboardsDir + `
`

// GrafanaProvisioning returns the files sind copies into
// /etc/grafana/provisioning before Grafana's first start, by path below
// it: the datasources, the dashboard provider and the dashboards.
func GrafanaProvisioning(realm string) map[string][]byte {
	files := map[string][]byte{
		"datasources/sind.yaml": []byte(grafanaDatasources(realm)),
		"dashboards/sind.yaml":  []byte(grafanaDashboardProvider),
	}
	rel := strings.TrimPrefix(DashboardsDir, grafanaProvisioning+"/")
	for name, content := range Dashboards() {
		files[path.Join(rel, name)] = content
	}
	return files
}

// serviceFiles returns the files sind copies into a service's container
// before its first start: the directory, and the files by path below it,
// readable by the user the service runs as.
func serviceFiles(realm string, s Service, alloyConfig string) (string, map[string]docker.File) {
	file := func(content []byte) docker.File { return docker.File{Content: content, Mode: 0o644} }
	switch s {
	case ServiceGrafana:
		files := make(map[string]docker.File)
		for name, content := range GrafanaProvisioning(realm) {
			files[name] = file(content)
		}
		return grafanaProvisioning, files
	case ServicePrometheus:
		return path.Dir(prometheusConfigPath), map[string]docker.File{path.Base(prometheusConfigPath): file([]byte(prometheusConfig))}
	case ServiceLoki:
		return path.Dir(lokiConfigPath), map[string]docker.File{path.Base(lokiConfigPath): file([]byte(lokiConfig))}
	default:
		return path.Dir(AlloyConfigPath), map[string]docker.File{path.Base(AlloyConfigPath): file([]byte(alloyConfig))}
	}
}
