// AlloyConfigPath is the configuration file sind writes into the Alloy
// container, before its first start and at every sync.
const AlloyConfigPath = "/etc/alloy/sind.alloy"

// slurmEndpoint is a slurmctld metrics endpoint the stack scrapes.
type slurmEndpoint struct {
	component, path, interval string
}

// slurmEndpoints are slurmctld's OpenMetrics endpoints. Slurm's guide
// advises 60-120 s and warns that jobs-users-accts grows with the users;
// sind clusters are small, and their users the ones the config declares.
var slurmEndpoints = []slurmEndpoint{
	{"slurm_jobs", "/metrics/jobs", "30s"},
	{"slurm_nodes", "/metrics/nodes", "30s"},
	{"slurm_partitions", "/metrics/partitions", "30s"},
	{"slurm_scheduler", "/metrics/scheduler", "30s"},
	{"slurm_users", "/metrics/jobs-users-accts", "60s"},
}

// alloyWriter writes Alloy configuration.
type alloyWriter struct {
	b      strings.Builder
	indent int
}

// line writes one line at the current indentation.
func (w *alloyWriter) line(format string, args ...any) {
	if format != "" {
		w.b.WriteString(strings.Repeat("  ", w.indent))
		fmt.Fprintf(&w.b, format, args...)
	}
	w.b.WriteString("\n")
}

// open writes the first line of a block and indents what follows.
func (w *alloyWriter) open(format string, args ...any) {
	w.line(format+" {", args...)
	w.indent++
}

// close ends a block.
func (w *alloyWriter) close() {
	w.indent--
	w.line("}")
}

// q returns s as an Alloy string literal: Alloy strings take Go's escapes.
func q(s string) string {
	return strconv.Quote(s)
}

// labelMap returns an Alloy object of string labels, keys in the order
// given as pairs.
func labelMap(pairs ...string) string {
	parts := make([]string, 0, len(pairs)/2)
	for i := 0; i+1 < len(pairs); i += 2 {
		parts = append(parts, q(pairs[i])+" = "+q(pairs[i+1]))
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// nodeLabels returns the labels every series and log line of a node has.
func nodeLabels(t Target) []string {
	return []string{"cluster", t.Cluster, "node", t.Node, "role", string(t.Role)}
}

// GenerateAlloyConfig returns Alloy's configuration for a realm's
// monitored nodes, under the daemon's cgroup driver (see CgroupPath):
//
//   - prometheus.scrape of slurmctld's metrics endpoints on every managed
//     controller, by container name on the mesh network, without following
//     redirects: a standby controller answers 303, so up is 1 only on the
//     controller in control;
//   - prometheus.exporter.blackbox with the Slurm daemon probes of
//     Collect;
//   - prometheus.exporter.cadvisor on the nodes' cgroups, read from the
//     host's cgroup tree, and a relabeling of its series to the cluster,
//     node and role, and the cgroup below the node, from which the job_id
//     and unit labels come;
//   - a loki.source.journal per node, on its directory of the journal
//     volume, with the unit and level of each entry, the level parsed
//     from the message for the Slurm daemons and MariaDB, which log all
//     their lines at priority info;
//   - remote writes to Prometheus and Loki by container name.
//
// Every series and log line carries realm, cluster and node, so a
// dashboard can link a panel to the matching logs.
func GenerateAlloyConfig(realm, cgroupDriver string, targets []Target) string {
	targets = sortTargets(targets)
	w := &alloyWriter{}
	w.line("// Generated by sind for realm %s from its node containers that mount %s.", q(realm), JournalVolume(realm))
	w.line("// sind rewrites this file and reloads Alloy; do not edit.")
	w.line("")

	w.open(`prometheus.remote_write "local"`)
	w.open("endpoint")
	w.line("url = %s", q("http://"+string(ContainerName(realm, ServicePrometheus))+":"+PrometheusPort+"/api/v1/write"))
	w.close()
	w.line("external_labels = %s", labelMap("realm", realm))
	w.close()

	writeSlurmScrapes(w, targets)
	writeChecks(w, targets)
	writeCadvisor(w, cgroupDriver, targets)
	writeJournals(w, realm, targets)

	w.line("")
	w.open(`loki.write "local"`)
	w.open("endpoint")
	w.line("url = %s", q("http://"+string(ContainerName(realm, ServiceLoki))+":"+LokiPort+"/loki/api/v1/push"))
	w.close()
	w.close()
	return w.b.String()
}

// writeSlurmScrapes writes a scrape of each slurmctld endpoint over the
// targets with SlurmMetrics, none without such a target.
func writeSlurmScrapes(w *alloyWriter, targets []Target) {
	var controllers []Target
	for _, t := range targets {
		if Collect(t.Role, t.Managed).SlurmMetrics {
			controllers = append(controllers, t)
		}
	}
	if len(controllers) == 0 {
		return
	}
	for _, e := range slurmEndpoints {
		w.line("")
		w.open("prometheus.scrape %s", q(e.component))
		w.line("targets = [")
		w.indent++
		for _, t := range controllers {
			w.line("%s,", labelMap(append([]string{"__address__", string(t.Container) + ":" + slurmctldPort}, nodeLabels(t)...)...))
		}
		w.indent--
		w.line("]")
		w.line("job_name         = %s", q(e.component))
		w.line("metrics_path     = %s", q(e.path))
		w.line("scrape_interval  = %s", q(e.interval))
		w.line("follow_redirects = false")
		w.line("forward_to       = [prometheus.remote_write.local.receiver]")
		w.close()
	}
}

// writeChecks writes the blackbox exporter with the targets' Slurm daemon
// probes and its scrape, none without a probe.
func writeChecks(w *alloyWriter, targets []Target) {
	var lines []func()
	for _, t := range targets {
		for _, c := range Collect(t.Role, t.Managed).Checks {
			address := string(t.Container) + ":" + c.Port
			if c.Module == "http" {
				address = "http://" + address + c.Path
			}
			labels := append(nodeLabels(t), "service", c.Service, "check", c.Check)
			lines = append(lines, func() {
				w.open("target")
				w.line("name    = %s", q(componentName(t.Cluster, t.Node)+"_"+c.Service+"_"+c.Check))
				w.line("address = %s", q(address))
				w.line("module  = %s", q(c.Module))
				w.line("labels  = %s", labelMap(labels...))
				w.close()
			})
		}
	}
	if len(lines) == 0 {
		return
	}
	w.line("")
	w.open(`prometheus.exporter.blackbox "slurm"`)
	w.line("config = %s", q("{ modules: { http: { prober: http, timeout: 5s }, tcp: { prober: tcp, timeout: 5s } } }"))
	for _, l := range lines {
		l()
	}
	w.close()
	w.line("")
	w.open(`prometheus.scrape "slurm_health"`)
	w.line("targets         = prometheus.exporter.blackbox.slurm.targets")
	w.line("job_name        = %s", q("slurm_health"))
	w.line("scrape_interval = %s", q("15s"))
	w.line("forward_to      = [prometheus.remote_write.local.receiver]")
	w.close()
}

// cgroupBelowNode matches a node's cgroup and captures the path below it,
// under either cgroup driver.
const cgroupBelowNode = `/(?:system\.slice/docker-[0-9a-f]+\.scope|docker/[0-9a-f]+)(/.*)?`

// writeCadvisor writes the cAdvisor exporter on the targets' cgroups, its
// scrape and the relabeling of its series, none without a target. Series
// of cgroups that are no node's (the root cgroup) are dropped.
func writeCadvisor(w *alloyWriter, driver string, targets []Target) {
	if len(targets) == 0 {
		return
	}
	w.line("")
	w.open(`prometheus.exporter.cadvisor "nodes"`)
	w.line("docker_only = false")
	w.line("raw_cgroup_prefix_allowlist = [")
	w.indent++
	for _, t := range targets {
		w.line("%s, // %s", q(CgroupPath(driver, t.ContainerID)), t.Container)
	}
	w.indent--
	w.line("]")
	w.line("store_container_labels = false")
	w.close()

	w.line("")
	w.open(`prometheus.scrape "cgroups"`)
	w.line("targets         = prometheus.exporter.cadvisor.nodes.targets")
	w.line("job_name        = %s", q("cgroups"))
	w.line("scrape_interval = %s", q("15s"))
	w.line("forward_to      = [prometheus.relabel.nodes.receiver]")
	w.close()

	w.line("")
	w.open(`prometheus.relabel "nodes"`)
	w.line("forward_to = [prometheus.remote_write.local.receiver]")
	for _, t := range targets {
		regex := regexp.QuoteMeta(CgroupPath(driver, t.ContainerID)) + "(/.*)?"
		labels := nodeLabels(t)
		for i := 0; i < len(labels); i += 2 {
			w.open("rule")
			w.line(`source_labels = ["id"]`)
			w.line("regex         = %s", q(regex))
			w.line("target_label  = %s", q(labels[i]))
			w.line("replacement   = %s", q(labels[i+1]))
			w.close()
		}
	}
	for _, r := range []struct{ source, regex, target, replacement string }{
		{"id", cgroupBelowNode, "cgroup", "$1"},
		{"cgroup", `.*/job_([0-9]+)(/.*)?`, "job_id", "$1"},
		{"cgroup", `.*/([^/]+\.service)`, "unit", "$1"},
	} {
		w.open("rule")
		w.line("source_labels = [%s]", q(r.source))
		w.line("regex         = %s", q(r.regex))
		w.line("target_label  = %s", q(r.target))
		w.line("replacement   = %s", q(r.replacement))
		w.close()
	}
	w.open("rule")
	w.line(`source_labels = ["node"]`)
	w.line(`regex         = ""`)
	w.line(`action        = "drop"`)
	w.close()
	w.close()
}

// slurmUnits matches the units of the Slurm daemons, which log every line
// at priority info with the level in the message.
const slurmUnits = `(slurmctld|slurmd|slurmdbd|sackd|slurmrestd)[.]service`

// slurmLevel matches the level a Slurm daemon prefixes a message with,
// after an optional timestamp and program name.
const slurmLevel = `^(?:\[[^\]]*\] )?(?:[a-z]+: )?(?P<level>fatal|error|warning|debug)[2-5]?: `

// mariadbLevel matches the level MariaDB brackets in a message.
const mariadbLevel = `\[(?P<level>ERROR|Warning|Note)\]`

// writeJournals writes a journal source per target and the relabeling and
// processing their entries go through, none without a target.
func writeJournals(w *alloyWriter, realm string, targets []Target) {
	if len(targets) == 0 {
		return
	}
	for _, t := range targets {
		w.line("")
		w.open("loki.source.journal %s", q(componentName(t.Cluster, t.Node)))
		w.line("path          = %s", q(JournalDir+"/"+JournalSubpath(t.Cluster, t.Node)))
		w.line("labels        = %s", labelMap(append([]string{"realm", realm}, nodeLabels(t)...)...))
		w.line("relabel_rules = loki.relabel.journal.rules")
		w.line("forward_to    = [loki.process.levels.receiver]")
		w.close()
	}

	// The unit is the entry's systemd unit, or, for what PID 1 logs about
	// a unit ("Started", "Failed with result"), that unit, as journalctl
	// -u and so sind logs show them.
	w.line("")
	w.open(`loki.relabel "journal"`)
	w.line("forward_to = []")
	for _, r := range []struct{ source, regex, target string }{
		{"__journal__systemd_unit", "(.+)", "unit"},
		{"__journal_unit", "(.+)", "unit"},
		{"__journal_priority_keyword", "(.+)", "level"},
	} {
		w.open("rule")
		w.line("source_labels = [%s]", q(r.source))
		w.line("regex         = %s", q(r.regex))
		w.line("target_label  = %s", q(r.target))
		w.close()
	}
	w.close()

	// Slurm prefixes a line's level, "fatal:" mapping to crit, "error:" to err and
	// "debug2:" to debug, as journal priority keywords name them; info
	// and verbose lines have none. MariaDB brackets it. Each match takes
	// only the lines with a level, so that the others keep the level of
	// their journal priority.
	w.line("")
	w.open(`loki.process "levels"`)
	w.line("forward_to = [loki.write.local.receiver]")
	for _, m := range []struct{ selector, expression, template string }{
		{
			`{unit=~"` + slurmUnits + `"} |~ ` + strconv.Quote(slurmLevel),
			slurmLevel,
			`{{ if eq .Value "fatal" }}crit{{ else if eq .Value "error" }}err{{ else }}{{ .Value }}{{ end }}`,
		},
		{
			`{unit="mariadb.service"} |~ ` + strconv.Quote(mariadbLevel),
			mariadbLevel,
			`{{ if eq .Value "ERROR" }}err{{ else if eq .Value "Warning" }}warning{{ else }}info{{ end }}`,
		},
	} {
		w.open("stage.match")
		w.line("selector = %s", q(m.selector))
		w.open("stage.regex")
		w.line("expression = %s", q(m.expression))
		w.close()
		w.open("stage.template")
		w.line(`source   = "level"`)
		w.line("template = %s", q(m.template))
		w.close()
		w.open("stage.labels")
		w.line(`values = { "level" = "" }`)
		w.close()
		w.close()
	}
	w.close()
}
