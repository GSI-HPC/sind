func TestBuildCreateCluster_After(t *testing.T) {
	f := valid("db", "on", "submitter", "on")
	rows(f, UserRows, "u0", "name", "alice", "accounts", "physics", "admin", "operator", "groups", "hpc")
	rows(f, GroupRows, "g0", "name", "hpc", "gid", "3000")
	rows(f, AccountRows, "a0", "name", "physics", "lk", "MaxJobs", "lv", "4")
	cmd, err := build(t, "create-cluster", f)
	require.NoError(t, err)
	require.Empty(t, cmd.Problems)

	assert.Equal(t, []Step{
		{Where: "On controller,db,submitter,worker-[0-1]: the users and groups", Lines: []string{
			"groupadd --gid 1000 alice",
			"groupadd --gid 3000 hpc",
			"useradd --uid 1000 --gid 1000 --groups hpc --home-dir /home/alice --no-create-home --shell /bin/bash alice",
		}},
		{Where: "On the controller, once slurmdbd knows the cluster: the Slurm accounts", Lines: []string{
			"sacctmgr -i add account physics MaxJobs=4",
			"sacctmgr -i add user alice account=physics defaultaccount=physics adminlevel=operator",
		}},
	}, cmd.After)
	assert.Contains(t, cmd.SlurmConf, "# Generated by sind\nClusterName=hpc\n")
	assert.Contains(t, cmd.SlurmConf, "AccountingStorageType=accounting_storage/slurmdbd\n", "the db node turns accounting on")
	assert.Contains(t, cmd.SlurmConf, "include /etc/slurm/sind-nodes.conf\n\n# /etc/slurm/sind-nodes.conf\n# Generated by sind\nNodeName=")
	assert.Contains(t, cmd.SlurmConf, "PartitionName=all Nodes=worker-0,worker-1 Default=YES")
}

func TestBuildCreateCluster_AfterVariants(t *testing.T) {
	t.Run("no users, no accounts", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", valid())
		require.NoError(t, err)
		assert.Empty(t, cmd.After)
		assert.NotEmpty(t, cmd.SlurmConf)
	})
	t.Run("clientIds", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", rows(valid("identity", "clientIds", "submitter", "on"), UserRows, "u0", "name", "alice"))
		require.NoError(t, err)
		require.Len(t, cmd.After, 1)
		assert.Equal(t, "On submitter: the users and groups", cmd.After[0].Where, "only the login node gets the users")
	})
	t.Run("unmanaged", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", rows(valid("controller-unmanaged", "on"), UserRows, "u0", "name", "alice"))
		require.NoError(t, err)
		require.Len(t, cmd.After, 1)
		assert.Equal(t, "On controller,worker-[0-1]: the users and groups", cmd.After[0].Where)
		assert.Empty(t, cmd.SlurmConf, "sind writes no Slurm config for an unmanaged cluster")
	})
	t.Run("db without accounts", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", valid("db", "on"))
		require.NoError(t, err)
		assert.Empty(t, cmd.After)
	})
	t.Run("config with an error", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", rows(valid(), UserRows, "u0", "name", "alice", "group", "nope"))
		require.NoError(t, err)
		require.NotEmpty(t, cmd.Problems)
		assert.Empty(t, cmd.After)
		assert.Empty(t, cmd.SlurmConf)
	})
	t.Run("bad name", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", valid("name", "Hpc"))
		require.NoError(t, err)
		assert.Empty(t, cmd.SlurmConf, "no preview of a name that sind refuses")
	})
	t.Run("YAML", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", yamlForm("kind: Cluster\nname: lab\n"))
		require.NoError(t, err)
		assert.Contains(t, cmd.SlurmConf, "ClusterName=lab\n")
	})
	t.Run("YAML bad name", func(t *testing.T) {
		cmd, err := build(t, "create-cluster", yamlForm("kind: Cluster\nname: dev\n"))
		require.NoError(t, err)
		assert.Empty(t, cmd.SlurmConf)
	})
}

func TestAfterCreate_SlurmConfFails(t *testing.T) {
	was := slurmConfFiles
	t.Cleanup(func() { slurmConfFiles = was })
	slurmConfFiles = func(*config.Cluster) (string, string, error) { return "", "", errors.New("no") }
	cmd, err := build(t, "create-cluster", valid())
	require.NoError(t, err)
	assert.Empty(t, cmd.SlurmConf)
}

func TestFoldNames(t *testing.T) {
	assert.Equal(t, "controller,worker-[0-2]", foldNames([]string{"controller", "worker-0", "worker-1", "worker-2"}))
	assert.Equal(t, "a[, b", foldNames([]string{"a[", "b"}), "names that are no node set stay as they are")
}
