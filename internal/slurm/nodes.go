// ManagedWorkers returns the sind-nodes.conf entries of a cluster's managed
// workers, in config order. Workers are named worker-0, worker-1, ...
// across all worker groups, unmanaged ones included, which get no entry.
// The Slurm CPUs and RealMemory of a worker are its container's CPU and
// memory limits; a memory limit that config.MemoryMB rejects is an error.
func ManagedWorkers(nodes []config.Node) ([]NodeEntry, error) {
	var workers []NodeEntry
	idx := 0
	for _, n := range nodes {
		if n.Role != config.RoleWorker {
			continue
		}
		count := max(n.Count, 1)
		first := idx
		idx += count
		if n.Managed != nil && !*n.Managed {
			continue
		}
		memMB, err := config.MemoryMB(n.Memory)
		if err != nil {
			return nil, fmt.Errorf("worker-%d: invalid memory %q: %w", first, n.Memory, err)
		}
		for i := first; i < idx; i++ {
			workers = append(workers, NodeEntry{Name: fmt.Sprintf("worker-%d", i), CPUs: n.CPUs, MemoryMB: memMB})
		}
	}
	return workers, nil
}

// DefMemPerCPU returns the default memory per allocated CPU, in MB, that
// lets every managed worker run a job on each of its CPUs: the smallest
// RealMemory/CPUs over the workers, rounded down. Slurm's default
// select/cons_tres treats memory as a consumable resource, and without a
// default a job that does not ask for memory gets all of a node's memory,
// so a worker would run one such job at a time whatever its CPUs. It
// returns 0, for none, without workers or with a worker that has less
// than 1 MB per CPU.
func DefMemPerCPU(workers []NodeEntry) int {
	perCPU, found := 0, false
	for _, w := range workers {
		if m := w.MemoryMB / max(w.CPUs, 1); !found || m < perCPU {
			perCPU, found = m, true
		}
	}
	return perCPU
}

// GenerateNodesConf generates the sind-nodes.conf content with a NodeName
// line for each managed worker (see ManagedWorkers) and the partition all
// with every one of them. Partition all is the default partition unless
// the main section declares another one (see declaresDefaultPartition):
// slurm.conf includes sind-nodes.conf after the main section, and of
// several default partitions slurmctld takes the last. It is
// AddNodesToConf on a file that holds only the header.
func GenerateNodesConf(workers []NodeEntry, main config.Section) string {
	return AddNodesToConf("# Generated by sind\n", workers, main)
}

// PartitionAll is the partition that sind puts every managed worker in.
const PartitionAll = "all"

// newPartitionLine returns the line of partition all with the given nodes.
// It sets only Default, so that PartitionName=DEFAULT lines in the main
// section apply to everything else, such as MaxTime and State, whose Slurm
// defaults are INFINITE and UP.
func newPartitionLine(nodes []string, isDefault bool) string {
	flag := "YES"
	if !isDefault {
		flag = "NO"
	}
	return "PartitionName=" + PartitionAll + " " + nodesPair(nodes) + " Default=" + flag
}

// escapePair escapes the characters of a slurm.conf value that Slurm's
// parser, and config.LinePairs, take for something else: a "#" starts a
// comment, and a backslash escapes the next character.
var escapePair = strings.NewReplacer(`\`, `\\`, "#", `\#`)

// pairText returns the pair key=value as slurm.conf takes it: the value
// escaped (see escapePair), and in double quotes when it is empty or
// holds a blank.
func pairText(key, value string) string {
	value = escapePair.Replace(value)
	if value == "" || strings.ContainsAny(value, " \t") {
		value = `"` + value + `"`
	}
	return key + "=" + value
}

// nodesPair returns the Nodes= pair of a partition with the given nodes.
// The names of sind's nodes need no escape; a node that a user defined in
// sind-nodes.conf may.
func nodesPair(nodes []string) string {
	return pairText("Nodes", strings.Join(nodes, ","))
}

// pairPattern matches the first key=value pair of a slurm.conf line that
// holds no backslash, as config.LinePairs reads it, with the bounds of the
// pair and of its key: blanks around the "=", an optional operator before
// it, and a value in double quotes or up to the next blank.
var pairPattern = regexp.MustCompile(`^\s*(([[:alnum:]_.]+)\s*[-*+/]?=\s*(?:"[^"]*"|\S+))(?:\s|$)`)

// pair is a key=value pair of a line: its key, and where it starts and
// ends in the line.
type pair struct {
	key        string
	start, end int
}

// linePairs returns the pairs of code, a slurm.conf line without its
// comment and without a backslash, in order: the pairs that
// config.LinePairs returns for it.
func linePairs(code string) []pair {
	var pairs []pair
	for at := 0; ; {
		m := pairPattern.FindStringSubmatchIndex(code[at:])
		if m == nil {
			return pairs
		}
		pairs = append(pairs, pair{key: code[at+m[4] : at+m[5]], start: at + m[2], end: at + m[3]})
		at += m[1]
	}
}

// partitionLine returns old, the earlier line of partition all, with its
// Nodes= list replaced by nodes, so that other changes to the line
// survive. Of several Nodes= pairs it replaces the last, which is the one
// Slurm takes. A line without a Nodes= pair gets one after its name. A
// comment at the end of the line stays as it is.
//
// A backslash makes Slurm, and config.LinePairs, read another line than
// the one written: such a line is written anew from its pairs (see
// rewritePartitionLine).
func partitionLine(old string, nodes []string) string {
	list := nodesPair(nodes)
	code := config.StripComment(old)
	if strings.Contains(code, `\`) {
		if comment := old[len(code):]; comment != "" {
			return rewritePartitionLine(code, list) + " " + comment
		}
		return rewritePartitionLine(code, list)
	}
	pairs := linePairs(code)
	for _, p := range slices.Backward(pairs[1:]) {
		if strings.EqualFold(p.key, "Nodes") {
			return old[:p.start] + list + old[p.end:]
		}
	}
	name := pairs[0].end
	return old[:name] + " " + list + old[name:]
}

// rewritePartitionLine returns the line of partition all whose code,
// the line without its comment, holds a backslash: its name, list, the
// Nodes= pair to give it, and its other pairs as config.LinePairs reads
// them, in their order. An operator before a "=" is not kept.
func rewritePartitionLine(code, list string) string {
	parts := []string{"PartitionName=" + PartitionAll, list}
	for _, p := range config.LinePairs(code)[1:] {
		if !strings.EqualFold(p[0], "Nodes") {
			parts = append(parts, pairText(p[0], p[1]))
		}
	}
	return strings.Join(parts, " ")
}

// declaresDefaultPartition reports whether slurm.conf content, such as the
// main section, declares a default partition of its own: a PartitionName
// line, other than PartitionName=DEFAULT, with a true Default (YES, UP,
// TRUE or 1).
func declaresDefaultPartition(conf config.Section) bool {
	for line := range conf.Lines() {
		pairs := config.LinePairs(line)
		if len(pairs) == 0 || !strings.EqualFold(pairs[0][0], "PartitionName") || strings.EqualFold(pairs[0][1], "DEFAULT") {
			continue
		}
		for _, p := range pairs[1:] {
			if strings.EqualFold(p[0], "Default") && slices.ContainsFunc([]string{"yes", "up", "true", "1"}, func(v string) bool { return strings.EqualFold(v, p[1]) }) {
				return true
			}
		}
	}
	return false
}

// NodeEntry represents a single node to add to sind-nodes.conf.
type NodeEntry struct {
	Name     string
	CPUs     int
	MemoryMB int
}

// AddNodesToConf adds node definitions to existing sind-nodes.conf content.
// A node that already has a NodeName line, such as one a failed
// `sind create worker` left behind, gets its line replaced, as Slurm
// refuses to start with a node defined twice; the other nodes get new
// lines. The Nodes= list of partition all is updated to include both
// existing and new nodes, each once; the rest of its line, and every other
// line, stays (see partitionLine). Content without that line, as
// RemoveNodesFromConf leaves it without managed nodes, gets a new one, the
// default partition unless conf, the cluster's slurm.conf as ReadSlurmConf
// returns it, declares another one (see GenerateNodesConf).
func AddNodesToConf(existing string, nodes []NodeEntry, conf config.Section) string {
	lines := strings.Split(strings.TrimRight(existing, "\n"), "\n")

	added := make(map[string]string, len(nodes))
	for _, n := range nodes {
		added[n.Name] = fmt.Sprintf("NodeName=%s CPUs=%d RealMemory=%d State=UNKNOWN",
			n.Name, n.CPUs, n.MemoryMB)
	}

	var managed []string
	var kept []string
	listed := make(map[string]bool)
	var partition string

	for _, line := range lines {
		if isPartitionAll(line) {
			partition = line
			continue // will be regenerated
		}
		name, isNode := nodeName(line)
		if !isNode {
			kept = append(kept, line)
			continue
		}
		if listed[name] {
			continue // a duplicate definition
		}
		listed[name] = true
		managed = append(managed, name)
		if def, ok := added[name]; ok {
			line = def
		}
		kept = append(kept, line)
	}

	for _, n := range nodes {
		if listed[n.Name] {
			continue
		}
		listed[n.Name] = true
		kept = append(kept, added[n.Name])
		managed = append(managed, n.Name)
	}

	if len(managed) > 0 {
		if partition == "" {
			kept = append(kept, newPartitionLine(managed, !declaresDefaultPartition(conf)))
		} else {
			kept = append(kept, partitionLine(partition, managed))
		}
	}

	return strings.Join(kept, "\n") + "\n"
}

// nodeName returns the node a NodeName line defines, and whether line is
// one. A NodeName=DEFAULT line sets defaults for the lines after it and
// defines no node.
func nodeName(line string) (string, bool) {
	pairs := config.LinePairs(line)
	if len(pairs) == 0 || !strings.EqualFold(pairs[0][0], "NodeName") || strings.EqualFold(pairs[0][1], "DEFAULT") {
		return "", false
	}
	return pairs[0][1], true
}

// isPartitionAll reports whether line is the line of partition all, the
// one sind puts every managed worker in. Other partition lines stay as
// they are.
func isPartitionAll(line string) bool {
	pairs := config.LinePairs(line)
	return len(pairs) > 0 && strings.EqualFold(pairs[0][0], "PartitionName") && pairs[0][1] == PartitionAll
}

// RemoveNodesFromConf removes the named nodes from existing sind-nodes.conf
// content. NodeName lines for the removed nodes are deleted and the Nodes=
// list of partition all is updated; the rest of its line, and every other
// line, stays (see partitionLine). The line of partition all goes with the
// last node, and content without one gets none.
func RemoveNodesFromConf(existing string, names []string) string {
	remove := make(map[string]bool, len(names))
	for _, n := range names {
		remove[n] = true
	}

	lines := strings.Split(strings.TrimRight(existing, "\n"), "\n")

	var managed []string
	var kept []string
	var partition string

	for _, line := range lines {
		if isPartitionAll(line) {
			partition = line
			continue // will be regenerated
		}
		if name, isNode := nodeName(line); isNode {
			if remove[name] {
				continue // skip removed node
			}
			managed = append(managed, name)
		}
		kept = append(kept, line)
	}

	if len(managed) > 0 && partition != "" {
		kept = append(kept, partitionLine(partition, managed))
	}

	return strings.Join(kept, "\n") + "\n"
}
